/**
 * Generates supabase/migrations/v1.8.7-rollback.sql from the CURRENT live
 * definitions, captured immediately before deploying v1.8.7.
 *
 * READ-ONLY against the database: it only runs pg_get_functiondef.
 *
 * The generated rollback:
 *   - restores each replaced function to the exact body running right now
 *   - drops the five helper functions v1.8.7 introduces
 *   - touches NO data table: no INSERT / UPDATE / DELETE / TRUNCATE / DROP TABLE
 *   - does NOT rewrite rotation_state, so no queue/quote/intake/audit data is lost
 */
import { readFileSync, writeFileSync } from "fs";
import { resolve } from "path";

const root = resolve(import.meta.dirname, "..", "..", "..", "..");
const env = {};
for (const line of readFileSync(resolve(root, ".env.local"), "utf-8").split("\n")) {
  const m = line.match(/^([^#=]+)=(.*)$/);
  if (m) env[m[1].trim()] = m[2].trim();
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function q(sql, attempt = 1) {
  const MAX = 5;
  let r;
  try {
    r = await fetch(
      `https://api.supabase.com/v1/projects/${env.SUPABASE_PROJECT_REF}/database/query`,
      {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          Authorization: `Bearer ${env.SUPABASE_ACCESS_TOKEN}`,
        },
        body: JSON.stringify({ query: sql }),
      },
    );
  } catch (netErr) {
    if (attempt < MAX) {
      console.log(`  network error, retry ${attempt}/${MAX - 1} in ${attempt * 3}s...`);
      await sleep(attempt * 3000);
      return q(sql, attempt + 1);
    }
    throw netErr;
  }

  const t = await r.text();
  if (!r.ok) {
    // 5xx from the gateway is transient; 4xx is a real SQL error.
    if (r.status >= 500 && attempt < MAX) {
      console.log(`  HTTP ${r.status} (transient), retry ${attempt}/${MAX - 1} in ${attempt * 3}s...`);
      await sleep(attempt * 3000);
      return q(sql, attempt + 1);
    }
    const brief = t.trimStart().startsWith("<") ? `${r.status} gateway error` : t.slice(0, 400);
    throw new Error(`HTTP ${r.status}: ${brief}`);
  }
  return JSON.parse(t);
}

// Functions v1.8.7 REPLACES (must be restored on rollback).
const REPLACED = [
  ["next_eligible_profile", "public.rotation_kind,integer"],
  ["pass_my_turn", "public.rotation_kind,text"],
  ["set_my_availability", "public.availability_status"],
  ["manager_set_rotation_eligibility", "uuid,public.rotation_kind,boolean,text"],
  ["claim_timed_quote", "uuid"],
  ["steal_timed_quote", "uuid"],
];

// Functions v1.8.7 INTRODUCES (must be dropped on rollback).
const INTRODUCED = [
  "public.advance_rotation(public.rotation_kind,uuid,integer,text,uuid,uuid,uuid,text)",
  "public.ensure_rotation_valid(public.rotation_kind,uuid)",
  "public.is_rotation_eligible(uuid,public.rotation_kind)",
  "public.rotation_position_of(uuid,public.rotation_kind)",
  "public.rotation_empty_reason(public.rotation_kind)",
];

const captured = [];
for (const [name, args] of REPLACED) {
  const rows = await q(`
    select pg_get_functiondef(p.oid) as def,
           coalesce(array_to_string(p.proacl::text[], ' | '), '<default>') as acl
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public'
      and p.oid = to_regprocedure('public.${name}(${args})');`);
  if (!rows.length) {
    console.error(`Could not capture public.${name}(${args}) — aborting.`);
    process.exit(1);
  }
  captured.push({ name, args, def: rows[0].def, acl: rows[0].acl });
  console.log(`captured public.${name}(${args})  [${rows[0].acl}]`);
}

// Confirm the helper functions are NOT already live (they must be new).
const existing = await q(`
  select p.proname from pg_proc p join pg_namespace n on n.oid=p.pronamespace
  where n.nspname='public' and p.proname in
    ('advance_rotation','ensure_rotation_valid','is_rotation_eligible',
     'rotation_position_of','rotation_empty_reason');`);
if (existing.length) {
  console.warn(
    `NOTE: helper(s) already present live: ${existing.map((r) => r.proname).join(", ")}`,
  );
}

const header = `-- New Hope Work Desk — ROLLBACK for v1.8.7-fix-rotation-integrity
--
-- AUTO-GENERATED by .kiro/specs/queue-rotation-integrity/scripts/generate-rollback.mjs
-- Captured from the LIVE database at ${new Date().toISOString()}
-- immediately before v1.8.7 was applied.
--
-- WHAT THIS DOES
--   * Restores the ${captured.length} replaced functions to the exact bodies that were
--     running in production before v1.8.7.
--   * Drops the ${INTRODUCED.length} helper functions v1.8.7 introduced.
--
-- WHAT THIS DELIBERATELY DOES NOT DO
--   * It does NOT rewrite public.rotation_state. A rotation left pointing at a
--     valid agent is harmless under the old functions, and rewriting it could
--     strand a live turn.
--   * It contains NO INSERT / UPDATE / DELETE / TRUNCATE / DROP TABLE.
--   * No quote, work item, intake, turn_events, quote_take_events, audit_log or
--     any other data row is read-modified-written. All history is preserved.
--
-- WARNING
--   Restoring these bodies REINTRODUCES the wraparound defect (RC-1): rotations
--   will again go NULL or stick on one agent whenever the current agent holds the
--   highest eligible position. Only run this if v1.8.7 caused a worse problem.
--
-- After running, re-run:
--   .kiro/specs/queue-rotation-integrity/diagnostics/production-queue-diagnostic.sql

begin;
`;

const parts = [header];

parts.push(`
-- ═══════════════════════════════════════════════════════════════════════════════
-- 1. Drop the helper functions introduced by v1.8.7.
--    Dropped AFTER the originals are restored below would fail on dependency, so
--    the restores come first and these drops run last (section 3).
-- ═══════════════════════════════════════════════════════════════════════════════
`);

parts.push(`
-- ═══════════════════════════════════════════════════════════════════════════════
-- 2. Restore the pre-v1.8.7 function bodies verbatim.
-- ═══════════════════════════════════════════════════════════════════════════════
`);

for (const c of captured) {
  parts.push(`
-- ── public.${c.name}(${c.args}) ──
-- Live ACL at capture time: ${c.acl}
${c.def.trimEnd()};
`);
}

parts.push(`
-- ═══════════════════════════════════════════════════════════════════════════════
-- 3. Drop the v1.8.7 helpers (now unreferenced by the restored bodies).
-- ═══════════════════════════════════════════════════════════════════════════════
`);
for (const sig of INTRODUCED) {
  parts.push(`drop function if exists ${sig};`);
}

parts.push(`

-- ═══════════════════════════════════════════════════════════════════════════════
-- 4. Restore grants exactly as captured above.
-- ═══════════════════════════════════════════════════════════════════════════════
grant execute on function public.next_eligible_profile(public.rotation_kind, integer) to anon, authenticated, service_role;
grant execute on function public.pass_my_turn(public.rotation_kind, text) to authenticated, service_role;
grant execute on function public.set_my_availability(public.availability_status) to authenticated, service_role;
grant execute on function public.manager_set_rotation_eligibility(uuid, public.rotation_kind, boolean, text) to authenticated, service_role;
grant execute on function public.claim_timed_quote(uuid) to authenticated, service_role;
grant execute on function public.steal_timed_quote(uuid) to authenticated, service_role;

-- ═══════════════════════════════════════════════════════════════════════════════
-- 5. Verify the rollback landed.
-- ═══════════════════════════════════════════════════════════════════════════════
do $verify$
begin
  if to_regprocedure('public.advance_rotation(public.rotation_kind,uuid,integer,text,uuid,uuid,uuid,text)') is not null then
    raise exception 'rollback incomplete: advance_rotation still exists';
  end if;
  if to_regprocedure('public.ensure_rotation_valid(public.rotation_kind,uuid)') is not null then
    raise exception 'rollback incomplete: ensure_rotation_valid still exists';
  end if;
  raise notice 'v1.8.7 rolled back. The RC-1 wraparound defect is now present again.';
end
$verify$;

commit;
`);

const out = parts.join("\n");

// Safety assertions on the generated file.
const decommented = out
  .split("\n")
  .map((l) => {
    const i = l.indexOf("--");
    return i === -1 ? l : l.slice(0, i);
  })
  .join("\n")
  .toLowerCase();

let scope = "";
let i = 0;
while (i < decommented.length) {
  const open = /\$[a-z_]*\$/i.exec(decommented.slice(i));
  if (!open) { scope += decommented.slice(i); break; }
  const openIdx = i + open.index;
  scope += decommented.slice(i, openIdx);
  const tag = open[0];
  const close = decommented.indexOf(tag, openIdx + tag.length);
  if (close === -1) break;
  i = close + tag.length;
}

for (const banned of [/\btruncate\b/, /\bdrop\s+table\b/, /\bdrop\s+schema\b/, /\bdelete\s+from\b/, /\balter\s+table\b/]) {
  if (banned.test(decommented)) {
    console.error(`Generated rollback contains a destructive statement: ${banned}`);
    process.exit(1);
  }
}
if (/\b(update|insert\s+into|delete\s+from)\b/.test(scope)) {
  console.error("Generated rollback performs a data write at top level — aborting.");
  process.exit(1);
}

const target = resolve(root, "supabase/migrations/v1.8.7-rollback.sql");
writeFileSync(target, out);
console.log(`\nWrote ${target} (${out.length} chars)`);
console.log("Safety checks passed: functions only, no data statements.");
