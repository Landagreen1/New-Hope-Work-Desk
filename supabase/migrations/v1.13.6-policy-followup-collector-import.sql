-- Spec: .kiro/specs/policy-follow-up-assignment-workflow
-- Requirements: 1.1, 1.2, 1.3, 1.4, 2.1, 2.2, 2.4, 2.5, 3.3, 4.1, 8.4, 11.2, 11.3, 13.1
-- Design: 11.1, 11.2
--
-- Forward-only. Two things:
--
--   1. `public.cancellation_import_batch` is replaced so it accepts the third column set,
--      `collector`. A consolidated collector export carries both halves of the legacy
--      eficacia/avisos pair, so it owns every field either half owned, plus contacts. The
--      merge logic itself is unchanged — this is the v1.10.10 body with each ownership
--      branch widened, generated by
--      `.kiro/specs/policy-follow-up-assignment-workflow/generate-collector-import-fn.mjs`
--      rather than retyped, and one extra `case_status` clause added for Requirement 8.4.
--
--      Both legacy paths keep behaving exactly as they did: `eficacia` and `avisos` still
--      own precisely the fields they owned, because every widened branch is
--      `in ('eficacia', 'collector')` or `in ('avisos', 'collector')` rather than a
--      reordering. The two-file transition path of the cancellations hardening spec is
--      untouched.
--
--   2. `public.renewal_import_collector_batch` is added beside `renewal_import_batch`. The
--      legacy Power BI / HawkSoft importer is left completely alone: it is still what the
--      current manager wizard calls, its column mapping still applies, and design 11.1's
--      requirement that a collector row not be labelled `powerbi` is met by having a
--      separate function that stamps `collector` and writes the source lineage.
--
-- ── What the renewal collector importer guarantees
--
--   * Re-import is idempotent (Requirement 2.4). Identity is `(policy_number, renewal_date)`,
--     the same pair the legacy importer uses, under the same advisory lock. A second run of
--     the same file updates source-owned facts and creates nothing.
--   * Source facts update; human work does not (Requirement 13.1). Notes, contacts, evidence,
--     the requote flag once set, a manager's `next_follow_up_at`, and a protected assignment
--     are never overwritten.
--   * A closed renewal is left closed (Requirement 2.5). Absence from a later file is not an
--     outcome, and neither is presence.
--   * Ownership follows the Requirement 3.3 precedence, by calling
--     `policy_followup_resolve_owner` per row after the upsert.
-- ═══════════════════════════════════════════════════════════════════════════════

